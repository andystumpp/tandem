using System.Text;
using System.Text.RegularExpressions;

namespace TaskList.Core;

/// <summary>
/// Background research for a task through the Claude Code CLI. Results are Markdown files in
/// %LOCALAPPDATA%\TaskList\research\, named after the task, so backlog.md stays about the work itself.
/// </summary>
public static partial class ResearchRunner
{
    [GeneratedRegex(@"[^a-z0-9]+")]
    private static partial Regex NonSlug();

    public static string ResearchFolder => Path.Combine(Path.GetDirectoryName(Preferences.DefaultPath)!, "research");

    public static string Slug(string text)
    {
        var slug = NonSlug().Replace(text.ToLowerInvariant(), "-").Trim('-');
        if (slug.Length > 60) slug = slug[..60].TrimEnd('-');
        return slug.Length == 0 ? "task" : slug;
    }

    public static string ResultPath(TaskItem task) => Path.Combine(ResearchFolder, Slug(task.Text) + ".md");

    public static bool HasResult(TaskItem task) => File.Exists(ResultPath(task));

    public static string BuildPrompt(TaskItem task, Area? area, IEnumerable<TaskItem> related)
    {
        var sb = new StringBuilder();
        sb.AppendLine("I keep a personal task list. Research the task below so I can act on it quickly.");
        sb.AppendLine("Reply in concise Markdown: a short summary, the concrete next steps, and links to the best sources.");
        sb.AppendLine("Do not ask me questions; make reasonable assumptions and state them.");
        sb.AppendLine();
        sb.AppendLine($"Task: {task.Text}");
        if (area != null)
        {
            sb.AppendLine($"Area: {area.Title}");
            if (area.Outcome.Length > 0) sb.AppendLine($"Outcome the area works towards: {area.Outcome}");
        }
        var others = related.Where(t => t != task && !t.Done).Take(10).ToList();
        if (others.Count > 0)
        {
            sb.AppendLine("Related open tasks:");
            foreach (var t in others) sb.AppendLine($"- {t.Text}");
        }
        foreach (var n in task.NoteLines) sb.AppendLine(n.Trim());
        return sb.ToString();
    }

    /// <summary>Runs the job and writes the result file; returns its path. Throws if the CLI fails.</summary>
    public static async Task<string> RunAsync(TaskItem task, Area? area, IEnumerable<TaskItem> related,
        CancellationToken cancellationToken = default)
    {
        var prompt = BuildPrompt(task, area, related);
        Directory.CreateDirectory(ResearchFolder);
        var output = await AiCli.RunAsync(prompt, ResearchFolder, ["WebSearch", "WebFetch"], cancellationToken: cancellationToken);
        var path = ResultPath(task);
        var body = $"# Research: {task.Text}\n\n_Generated by {AiCli.DisplayName} on {DateTime.Now:yyyy-MM-dd HH:mm}._\n\n{output}\n";
        await File.WriteAllTextAsync(path, body, new UTF8Encoding(false), cancellationToken);
        return path;
    }
}
